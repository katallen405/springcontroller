"""Generate a minimal SRDF of <disable_collisions> pairs for self-collision checking.

URDFArmConfiguration needs an SRDF to drop link pairs that are always in
contact (pinocchio's addAllCollisionPairs only skips pairs on the *same*
joint). For robots without a MoveIt config -- e.g. the Gen2 + Robotiq --
this produces one without the MoveIt Setup Assistant. Disabled:

* "Adjacent" pairs: links connected through at most one movable joint
  (any number of fixed joints), i.e. parent/child after merging
  rigidly-attached links.
* Every pair inside the gripper (links whose name starts with
  --gripper-prefix): the fingers touch each other by design.
* Any remaining pair in collision at --reference-deg (every arm joint at
  that angle, in Kinova degrees == URDF radians), so the arm's resting
  pose isn't flagged.

Usage:
    python3 make_srdf_disabled_pairs.py URDF OUT.srdf \
        --gripper-prefix gripper_ --lock gripper_finger1_joint ... \
        --reference-deg 180
"""

import argparse
import itertools
import math
import os
import sys
import xml.etree.ElementTree as ET

import numpy as np
import pinocchio as pin

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from springcontroller.urdf_arm_configuration import URDFArmConfiguration  # noqa: E402


def rigid_groups_and_adjacency(urdf_path: str) -> set[frozenset[str]]:
    root = ET.parse(urdf_path).getroot()
    links = [link.get("name") for link in root.findall("link")]
    joints = [(j.find("parent").get("link"), j.find("child").get("link"), j.get("type"))
              for j in root.findall("joint")]

    # Union-find over fixed joints: links in one group never move relative
    # to each other.
    group = {name: name for name in links}

    def find(x):
        while group[x] != x:
            group[x] = group[group[x]]
            x = group[x]
        return x
    for parent, child, jtype in joints:
        if jtype == "fixed":
            group[find(child)] = find(parent)

    adjacent_groups = {frozenset((find(p), find(c))) for p, c, t in joints if t != "fixed"}
    pairs = set()
    for a, b in itertools.combinations(links, 2):
        ga, gb = find(a), find(b)
        if ga == gb or frozenset((ga, gb)) in adjacent_groups:
            pairs.add(frozenset((a, b)))
    return pairs


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("urdf")
    ap.add_argument("out")
    ap.add_argument("--gripper-prefix", default="")
    ap.add_argument("--lock", nargs="*", default=[])
    ap.add_argument("--reference-deg", type=float, default=180.0)
    args = ap.parse_args()

    reasons: dict[frozenset[str], str] = {}
    for pair in rigid_groups_and_adjacency(args.urdf):
        reasons[pair] = "Adjacent"

    links = [link.get("name") for link in ET.parse(args.urdf).getroot().findall("link")]
    if args.gripper_prefix:
        grip = [n for n in links if n.startswith(args.gripper_prefix)]
        for a, b in itertools.combinations(grip, 2):
            reasons.setdefault(frozenset((a, b)), "Gripper")

    # Reference-pose collisions, using springcontroller's own loader so the
    # geometry simplification matches what runs live.
    full = pin.buildModelFromUrdf(args.urdf)
    reduced = pin.buildReducedModel(
        full, [full.getJointId(n) for n in args.lock], pin.neutral(full))
    q = pin.neutral(reduced)
    ref = math.radians(args.reference_deg)
    for jid in range(1, reduced.njoints):
        j = reduced.joints[jid]
        if j.nq == 2:
            q[j.idx_q:j.idx_q + 2] = [math.cos(ref), math.sin(ref)]
        else:
            q[j.idx_q] = ref
    arm = URDFArmConfiguration(args.urdf, "", q, locked_joint_names=args.lock)
    cm, cd = arm._collision_model, arm._collision_data
    pin.computeCollisions(arm._model, arm._model.createData(), cm, cd, np.asarray(q), False)
    for k, p in enumerate(cm.collisionPairs):
        if cd.collisionResults[k].isCollision():
            a = full.frames[cm.geometryObjects[p.first].parentFrame].name
            b = full.frames[cm.geometryObjects[p.second].parentFrame].name
            reasons.setdefault(frozenset((a, b)), "Default")

    robot = ET.Element("robot", name=ET.parse(args.urdf).getroot().get("name"))
    robot.append(ET.Comment(
        " Generated by springcontroller/tools/make_srdf_disabled_pairs.py. "
        "Only <disable_collisions>; no MoveIt groups. "))
    for pair, reason in sorted(reasons.items(), key=lambda kv: sorted(kv[0])):
        a, b = sorted(pair)
        ET.SubElement(robot, "disable_collisions", link1=a, link2=b, reason=reason)
    ET.indent(robot)
    ET.ElementTree(robot).write(args.out, xml_declaration=True, encoding="utf-8")
    counts = {r: list(reasons.values()).count(r) for r in set(reasons.values())}
    print(f"wrote {args.out}: {counts}")


if __name__ == "__main__":
    main()
